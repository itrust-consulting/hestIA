// Known inference parameters per LLM backend protocol, shown in the
// connection Settings modal. Each list is scoped to what that protocol's
// own API actually documents as a valid request-time parameter -- not
// everything a specific server implementation might additionally accept
// (e.g. vLLM's OpenAI-compatible server honors several non-standard extra
// fields, but those aren't guaranteed to exist on "OpenAI-compatible" in
// general, so they're deliberately left out here).

export type ParamType = 'number' | 'integer' | 'boolean' | 'text' | 'string-list' | 'object' | 'json';

export type ParamSpec = {
  key: string;
  label: string;
  type: ParamType;
  step?: number;
  // Populated for auto-generated OpenAI params; optional for hand-written ones.
  description?: string;
  // The provider's own documented default, shown as a hint -- leaving the
  // field blank still omits the key entirely (provider applies its default
  // itself); this is informational only, never used to pre-fill a value.
  default?: unknown;
  // Only present when type === 'object' -- flat nested sub-fields.
  fields?: ParamSpec[];
};

