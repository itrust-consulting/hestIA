export function getParamSpecs(
  backendType: 'ollama' | 'openai' | 'qdrant',
  purpose: 'generation' | 'embedding' | 'reranking' | 'vector_db',
): ParamSpec[] {
  if (backendType === 'qdrant') return purpose === 'vector_db' ? QDRANT_RETRIEVAL_PARAMS : [];
  return PARAM_SCHEMAS[backendType][purpose as 'generation' | 'embedding' | 'reranking'] ?? [];
}

export function paramValueToString(v: unknown): string {
  if (v == null) return '';
  if (Array.isArray(v)) return v.join(', ');
  return String(v);
}

export function parseParamValue(type: ParamType, raw: string): unknown {
  const trimmed = raw.trim();
  switch (type) {
    case 'boolean':
      return trimmed === 'true';
    case 'integer': {
      const n = parseInt(trimmed, 10);
      return Number.isNaN(n) ? undefined : n;
    }
    case 'number': {
      const n = Number(trimmed);
      return Number.isNaN(n) ? undefined : n;
    }
    case 'string-list':
      return trimmed
        .split(',')
        .map((s) => s.trim())
        .filter(Boolean);
    default:
      return raw;
  }
}

// Reconstructs a type: 'object' param's value from its flattened sub-field
// entries in a settingsParamValues-style map, keyed as `${spec.key}.${field.key}`.
// Returns undefined if none of the sub-fields were set.
export function buildObjectParam(spec: ParamSpec, values: Record<string, string>): Record<string, unknown> | undefined {
  const result: Record<string, unknown> = {};
  for (const field of spec.fields ?? []) {
    const raw = values[`${spec.key}.${field.key}`];
    if (!raw || raw.trim() === '') continue;
    const parsed = parseParamValue(field.type, raw);
    if (parsed === undefined) continue;
    if (Array.isArray(parsed) && parsed.length === 0) continue;
    result[field.key] = parsed;
  }
  return Object.keys(result).length === 0 ? undefined : result;
}

// Parses a type: 'json' param's raw textarea contents. Blank input is treated
// as "unset" rather than an error.
export function parseJsonParam(raw: string): { value?: unknown; error?: string } {
  const trimmed = raw.trim();
  if (trimmed === '') return {};
  try {
    return { value: JSON.parse(trimmed) };
  } catch {
    return { error: 'Invalid JSON' };
  }
}
